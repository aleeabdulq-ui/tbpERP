import "dotenv/config";
import express from "express";
import helmet from "helmet";
import cors from "cors";
import morgan from "morgan";
import cookieParser from "cookie-parser";
import rateLimit from "express-rate-limit";
import { config } from "./config.js";
import auth from "./modules/auth/auth.routes.js";
import dashboard from "./modules/dashboard/dashboard.routes.js";
import notifications from "./modules/notifications/notification.routes.js";
import tasks, { processDueReminders } from "./modules/tasks/task.routes.js";
import projects from "./modules/projects.routes.js";
import profile from "./modules/profile.routes.js";
import hr from "./modules/hr.routes.js";
import reports from "./modules/reports.routes.js";
import messages from "./modules/messages.routes.js";
import admin from "./modules/admin.routes.js";
import { errorHandler, notFound } from "./middleware/error.js";
import { prisma } from "./lib/prisma.js";

const app = express();
app.set("trust proxy", 1);
app.use(helmet());
app.use(cors({ origin: config.NODE_ENV === "development" ? [config.WEB_ORIGIN, "http://127.0.0.1:5173"] : config.WEB_ORIGIN, credentials: true }));
app.use(morgan(config.NODE_ENV === "production" ? "combined" : "dev"));
app.use(express.json({ limit: "1mb" }));
app.use(express.urlencoded({ extended: false }));
app.use(cookieParser());
app.use("/uploads", express.static("uploads", { dotfiles: "deny", index: false, maxAge: "1d" }));
app.use("/api/v1/auth", rateLimit({ windowMs: 15 * 60 * 1000, limit: 100, standardHeaders: "draft-7" }), auth);
app.use("/api/v1/dashboard", dashboard);
app.use("/api/v1/profile", profile);
app.use("/api/v1/hr", hr);
app.use("/api/v1/reports", reports);
app.use("/api/v1/messages", messages);
app.use("/api/v1/notifications", notifications);
app.use("/api/v1/tasks", tasks);
app.use("/api/v1/projects", projects);
app.use("/api/v1/admin", admin);
app.get("/health", async (_request, response) => { await prisma.$queryRaw`SELECT 1`; response.json({ status: "ok", timestamp: new Date().toISOString() }); });
app.use(notFound);
app.use(errorHandler);

const server = app.listen(config.PORT, () => console.log(`TBP ERP API listening on ${config.PORT}`));
const reminderTimer = setInterval(() => processDueReminders().catch((error) => console.error("Task reminder processing failed", error)), 60_000);
reminderTimer.unref();
const shutdown = () => { clearInterval(reminderTimer); server.close(async () => { await prisma.$disconnect(); process.exit(0); }); };
process.on("SIGTERM", shutdown);
process.on("SIGINT", shutdown);
